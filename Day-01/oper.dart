// arthemetic operations

void main() {
  int a = 10;
  int b = 5;

  // Addition
  int sum = a + b;
  print("Sum: $sum");

  // Subtraction
  int difference = a - b;
  print("Difference: $difference");

  // Multiplication
  int product = a * b;
  print("Product: $product");

  // Division
  double quotient = a / b;
  print("Quotient: $quotient");

  // Modulus
  int remainder = a % b;
  print("Remainder: $remainder");

//   comparison operators are used to compare two values and return a boolean result (true or false). They are commonly used in conditional statements and loops to make decisions based on certain conditions. Here are the comparison operators in Dart:

  int x = 10;
  int y = 5;

  // Equal to
  bool isEqual = x == y;
  print("Is Equal: $isEqual");

  // Not equal to
  bool isNotEqual = x != y;
  print("Is Not Equal: $isNotEqual");

  // Greater than
  bool isGreaterThan = x > y;
  print("Is Greater Than: $isGreaterThan");

  // Less than
  bool isLessThan = x < y;
  print("Is Less Than: $isLessThan");

  // Greater than or equal to
  bool isGreaterThanOrEqualTo = x >= y;
  print("Is Greater Than or Equal To: $isGreaterThanOrEqualTo");

  // Less than or equal to
  bool isLessThanOrEqualTo = x <= y;
  print("Is Less Than or Equal To: $isLessThanOrEqualTo");

  // Logical AND
  bool isTrue = true;
  bool isFalse = false;
  bool logicalAnd = isTrue && isFalse;
  print("Logical AND: $logicalAnd");

  // Logical OR
  bool logicalOr = isTrue || isFalse;
  print("Logical OR: $logicalOr");

  // Logical NOT
  bool logicalNot = !isTrue;
  print("Logical NOT: $logicalNot");
}